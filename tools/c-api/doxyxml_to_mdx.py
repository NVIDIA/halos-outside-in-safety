"""Convert Doxygen XML for the Safety Core headers into one Fern MDX page per header.

Usage: doxyxml_to_mdx.py <doxygen-xml-dir> <headers.tsv> <output-dir> <release>

Every page in <output-dir> is written from scratch, and the output is deterministic (members in
source order), so a regeneration only changes what the headers changed. Text from the header
comments is escaped for MDX; signatures and declarations go in code blocks or code spans.
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

XML_DIR, TSV, OUT_DIR, RELEASE = sys.argv[1:5]

GENERATED_NOTE = (
    "{/* Generated by tools/c-api/generate_pages.sh from the headers in safety-core/. "
    "Do not edit; changes are overwritten when the headers change. */}"
)


# ---------------------------------------------------------------------------- text rendering
def esc(text):
    """Escape plain text for MDX: no JSX, no expressions, no accidental Markdown."""
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("{", "&#123;").replace("}", "&#125;")
    text = re.sub(r"([\\*\[\]`#|])", r"\\\1", text)
    return text


def code_span(text):
    text = " ".join(text.split())
    if not text:
        return ""
    tick = "``" if "`" in text else "`"
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return f"{tick}{pad}{text}{pad}{tick}"


def inline(node):
    """Render the inline content of a Doxygen description node."""
    out = [esc(node.text or "")]
    for child in node:
        tag = child.tag
        if tag in ("computeroutput", "ref"):
            out.append(code_span("".join(child.itertext())))
        elif tag == "bold":
            out.append("**" + inline(child).strip() + "**")
        elif tag == "emphasis":
            out.append("*" + inline(child).strip() + "*")
        elif tag == "ulink":
            out.append(f"[{inline(child).strip()}]({child.get('url')})")
        elif tag == "linebreak":
            out.append(" ")
        elif tag in ("itemizedlist", "orderedlist", "simplesect", "parameterlist",
                     "programlisting", "verbatim"):
            pass  # block content, rendered by blocks()
        else:
            out.append(inline(child))
        out.append(esc(child.tail or ""))
    return re.sub(r"[ \t\r\n]+", " ", "".join(out))


def code_block(node, lang="c"):
    if node.tag == "programlisting":
        lines = ["".join(l.itertext()) for l in node.findall("codeline")]
    else:
        lines = "".join(node.itertext()).strip("\n").split("\n")
    return f"```{lang}\n" + "\n".join(lines).rstrip() + "\n```"


def blocks(desc, skip_params=False):
    """Render a brief/detailed description as Markdown blocks."""
    if desc is None:
        return []
    out = []
    for para in desc.findall("para"):
        text = inline(para).strip()
        if text:
            out.append(text)
        for child in para:
            if child.tag in ("itemizedlist", "orderedlist"):
                marker = "-" if child.tag == "itemizedlist" else "1."
                items = []
                for li in child.findall("listitem"):
                    body = " ".join(blocks(li)) or ""
                    items.append(f"{marker} {body}")
                out.append("\n".join(items))
            elif child.tag in ("programlisting", "verbatim"):
                out.append(code_block(child))
            elif child.tag == "simplesect":
                body = " ".join(blocks(child))
                kind = child.get("kind")
                label = {"return": "Returns", "note": "Note", "warning": "Warning",
                         "see": "See also", "pre": "Precondition", "post": "Postcondition",
                         "attention": "Attention", "since": "Since"}.get(kind, kind.capitalize())
                if body:
                    out.append(f"**{label}:** {body}")
            elif child.tag == "parameterlist" and not skip_params:
                rows = param_rows(child)
                if rows:
                    out.append(table(["Parameter", "Description"], rows))
    return out


def param_rows(plist):
    rows = []
    for item in plist.findall("parameteritem"):
        names = [code_span("".join(n.itertext())) for n in item.iter("parametername")]
        desc = " ".join(blocks(item.find("parameterdescription")))
        rows.append([", ".join(names), desc])
    return rows


def table(head, rows):
    def cell(v):
        return (v or "").replace("\n", " ").replace("|", "\\|")
    lines = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    lines += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def text_of(node):
    return " ".join("".join(node.itertext()).split()) if node is not None else ""


def description(member):
    parts = blocks(member.find("briefdescription")) + blocks(member.find("detaileddescription"))
    return parts


def one_line(member):
    return " ".join(description(member)).replace("\n", " ")


def line_of(member):
    loc = member.find("location")
    return int(loc.get("line", "0")) if loc is not None else 0


# ---------------------------------------------------------------------------- page sections
def render_function(m):
    static = "static " if m.get("static") == "yes" else ""
    inl = "inline " if m.get("inline") == "yes" else ""
    sig = f"{static}{inl}{text_of(m.find('type'))} {m.findtext('name')}{m.findtext('argsstring') or ''};"
    out = [f"### {esc(m.findtext('name'))}", "```c\n" + " ".join(sig.split()) + "\n```"]
    detailed = m.find("detaileddescription")
    out += blocks(m.find("briefdescription")) + blocks(detailed)
    return out


def render_enum(m):
    name = (m.findtext("name") or "").strip()
    values = [v.findtext("name") for v in m.findall("enumvalue")]
    if not name or name.startswith("@"):
        # An unnamed enum: title it by its values so the heading is unique and readable.
        out = [f"### Enumeration: {esc(', '.join(values))}",
               "```c\nenum { " + ", ".join(values) + " }\n```"]
    else:
        out = [f"### {esc(name)}", "```c\nenum " + name + "\n```"]
    out += description(m)
    rows = []
    for v in m.findall("enumvalue"):
        init = text_of(v.find("initializer")).lstrip("= ").strip()
        rows.append([code_span(v.findtext("name")), code_span(init), " ".join(description(v))])
    if rows:
        out.append(table(["Value", "Initializer", "Description"], rows))
    return out


def render_struct(refid):
    path = os.path.join(XML_DIR, refid + ".xml")
    root = ET.parse(path).getroot().find("compounddef")
    name = root.findtext("compoundname")
    kind = root.get("kind")
    out = [f"### {esc(name)}", f"```c\n{kind} {name}\n```"]
    out += blocks(root.find("briefdescription")) + blocks(root.find("detaileddescription"))
    fields = []
    for sd in root.findall("sectiondef"):
        for m in sorted(sd.findall("memberdef"), key=line_of):
            if m.get("kind") != "variable":
                continue
            decl = f"{text_of(m.find('type'))} {m.findtext('name')}{m.findtext('argsstring') or ''}"
            fields.append([code_span(m.findtext("name")), code_span(" ".join(decl.split())),
                           one_line(m)])
    if fields:
        out.append(table(["Field", "Declaration", "Description"], fields))
    return out, line_of(root)


def page_for(file_def, group, tsv_desc):
    name = file_def.findtext("compoundname")
    title_desc = re.sub(r"`", "", tsv_desc)
    front = ["---", f'title: "{name}"',
             'description: "' + f"Generated reference for {name}: {title_desc}".replace('"', "'") + '"',
             "---", GENERATED_NOTE, "", ""]
    body = [
        f"{esc_md(tsv_desc)}",
        f"Part of the {esc(group)}. Generated from the header published in `safety-core/`, "
        f"release {esc(RELEASE)}. The development packages install it in `/opt/nvidia/psf/include`.",
        f'```c\n#include "{name}"\n```',
    ]
    body += blocks(file_def.find("briefdescription")) + blocks(file_def.find("detaileddescription"))

    sections = {}
    for sd in file_def.findall("sectiondef"):
        for m in sd.findall("memberdef"):
            kind = "var" if m.get("kind") == "variable" else m.get("kind")
            sections.setdefault(kind, []).append(m)
    for k in sections:
        sections[k].sort(key=line_of)

    if sections.get("function"):
        body.append("## Functions")
        for m in sections["function"]:
            body += render_function(m)

    structs = []
    for inner in file_def.findall("innerclass"):
        rendered, line = render_struct(inner.get("refid"))
        structs.append((line, rendered))
    if structs or sections.get("enum") or sections.get("typedef"):
        body.append("## Types")
        for _, rendered in sorted(structs, key=lambda t: t[0]):
            body += rendered
        for m in sections.get("enum", []):
            body += render_enum(m)
        if sections.get("typedef"):
            body.append("### Type aliases")
            rows = [[code_span(m.findtext("name")),
                     code_span(" ".join((m.findtext("definition") or "").split())),
                     one_line(m)] for m in sections["typedef"]]
            body.append(table(["Name", "Definition", "Description"], rows))

    if sections.get("var"):
        body.append("## Constants")
        rows = []
        for m in sections["var"]:
            decl = f"{m.findtext('definition') or ''} {text_of(m.find('initializer'))}"
            rows.append([code_span(m.findtext("name")), code_span(" ".join(decl.split())), one_line(m)])
        body.append(table(["Name", "Declaration", "Description"], rows))

    if sections.get("define"):
        body.append("## Macros")
        rows = []
        for m in sections["define"]:
            params = [p.findtext("defname") for p in m.findall("param")]
            label = m.findtext("name") + (f"({', '.join(params)})" if m.findall("param") else "")
            rows.append([code_span(label), code_span(text_of(m.find("initializer"))), one_line(m)])
        body.append(table(["Macro", "Value", "Description"], rows))

    return "\n".join(front) + "\n\n".join(body) + "\n"


def esc_md(text):
    """Escape a headers.tsv description, keeping its `code` spans."""
    parts = re.split(r"(`[^`]*`)", text)
    return "".join(p if p.startswith("`") else esc(p) for p in parts)


def slug(header):
    return re.sub(r"[^a-z0-9]+", "-", header.lower()).strip("-")


def main():
    order, info = [], {}
    for line in open(TSV, encoding="utf-8"):
        if not line.strip() or line.startswith("#"):
            continue
        header, group, desc = line.rstrip("\n").split("\t")
        order.append(header)
        info[header] = (group, desc)

    index = ET.parse(os.path.join(XML_DIR, "index.xml")).getroot()
    files = {}
    for comp in index.findall("compound"):
        if comp.get("kind") == "file":
            root = ET.parse(os.path.join(XML_DIR, comp.get("refid") + ".xml")).getroot()
            files[comp.findtext("name")] = root.find("compounddef")

    os.makedirs(OUT_DIR, exist_ok=True)
    for old in os.listdir(OUT_DIR):
        if old.endswith(".mdx"):
            os.remove(os.path.join(OUT_DIR, old))
    written = 0
    for header in order:
        if header not in files:
            continue
        group, desc = info[header]
        with open(os.path.join(OUT_DIR, slug(header) + ".mdx"), "w", encoding="utf-8") as f:
            f.write(page_for(files[header], group, desc))
        written += 1
    print(f"wrote {written} page(s) to {OUT_DIR}")


if __name__ == "__main__":
    main()
